// Emit migration 017: add c1/c4 columns to viewing_spots and populate
// from skyfield-contacts.json (1s precision per spot's exact coords).
import fs from 'node:fs';
import path from 'node:path';

const data = JSON.parse(
  fs.readFileSync(path.resolve('scripts/internal/skyfield-contacts.json'), 'utf8')
);

const lines = [
  `-- Add per-spot C1 (partial begins) and C4 (partial ends) to viewing_spots,`,
  `-- populated from Skyfield at each spot's exact coordinates (1s precision).`,
  `--`,
  `-- Why this exists: previously C1/C4 were enriched at request time in`,
  `-- server/api/spots/[slug].get.ts via nearestGridPoint() against`,
  `-- public/eclipse-data/grid.json. With ~0.15deg grid step the nearest`,
  `-- point can be 5-10 km from the spot, giving C1/C4 drift of several`,
  `-- seconds. Storing per-spot values removes that drift entirely.`,
  `--`,
  `-- Generated by scripts/internal/gen-c1-c4-migration.mjs from`,
  `-- scripts/internal/skyfield-contacts.json (built by`,
  `-- scripts/internal/skyfield-contacts-all-spots.py). Re-run both to`,
  `-- refresh after adding/moving spots.`,
  ``,
  `ALTER TABLE viewing_spots`,
  `  ADD COLUMN IF NOT EXISTS c1 TIMESTAMPTZ,`,
  `  ADD COLUMN IF NOT EXISTS c4 TIMESTAMPTZ;`,
  ``,
];

// Sort by slug for stable diffs
const sorted = [...data.spots].sort((a, b) => a.slug.localeCompare(b.slug));
for (const s of sorted) {
  lines.push(
    `UPDATE viewing_spots SET c1 = '${s.c1}', c4 = '${s.c4}' WHERE slug = '${s.slug}';`
  );
}

fs.writeFileSync(
  path.resolve('scripts/migrations/017-spot-c1-c4-columns.sql'),
  lines.join('\n') + '\n'
);
console.log(`Wrote scripts/migrations/017-spot-c1-c4-columns.sql with ${sorted.length} UPDATEs`);
